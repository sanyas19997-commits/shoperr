<script>
// Newsletter popup: show ONCE per browser via localStorage flag.
(function () {
  var KEY = 'billaro_newsletter_seen';
  var popup = document.querySelector('.box-popup-newsletter');
  if (!popup) return;
  if (localStorage.getItem(KEY) === '1') {
    popup.parentNode.removeChild(popup);
    return;
  }
  // Kidify main.js auto-shows the popup; we add the dismiss-and-remember behavior.
  function dismiss() {
    try { localStorage.setItem(KEY, '1'); } catch (e) {}
    popup.style.display = 'none';
    setTimeout(function () {
      if (popup && popup.parentNode) popup.parentNode.removeChild(popup);
    }, 400);
  }
  popup.addEventListener('click', function (e) {
    var t = e.target;
    if (t.closest && (t.closest('.btn-close-popup-newsletter') || t.closest('.box-newsletter-overlay'))) {
      e.preventDefault();
      dismiss();
    }
  });
  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' && popup.style.display !== 'none') dismiss();
  });
})();
</script>
